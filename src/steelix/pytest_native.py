"""pytest plugin of `steelix test`: checks that the project's tests ran
against the native code (design §15).

`steelix test` copies this file into a directory of its own as
`steelix_native.py` and loads it with `-p steelix_native`, so it must only
use the standard library and pytest: it runs in the interpreter of the
program's virtual environment, which need not have steelix installed.

The program in the interpreter role puts its `NativeImporter` on
`sys.meta_path`. At the end of the session the plugin lists the transpiled
modules the tests imported, and fails the run if one of them came from its
Python source instead of the importer, or if there is no importer at all.
"""

from __future__ import annotations

import os
import sys

import pytest

NAME = "steelix_native"


def native_importer():
    for finder in sys.meta_path:
        if type(finder).__name__ == "NativeImporter":
            return finder
    return None


def loader_name(module) -> str:
    spec = getattr(module, "__spec__", None)
    loader = getattr(spec, "loader", None) or getattr(module, "__loader__", None)
    return type(loader).__name__


def within(path: str | None, root: str) -> bool:
    if not isinstance(path, str):
        return False
    path = os.path.realpath(path)
    return path == root or path.startswith(root + os.sep)


class NativeCheck:
    def __init__(self) -> None:
        self.importer = native_importer()
        self.problem: str | None = None

    def pytest_sessionfinish(self, session: pytest.Session) -> None:
        if self.importer is None:
            self.problem = (
                "no transpiled modules: the interpreter is not a program generated by "
                "steelix, or the program has no project modules"
            )
        elif source := self.from_source():
            self.problem = "transpiled modules imported from source: " + ", ".join(source)
        if self.problem is not None and session.exitstatus == 0:
            session.exitstatus = pytest.ExitCode.TESTS_FAILED

    def from_source(self) -> list[str]:
        names = set(self.importer.modules)
        return sorted(
            name
            for name, module in list(sys.modules.items())
            if name in names and loader_name(module) != "NativeLoader"
        )

    def pytest_terminal_summary(self, terminalreporter) -> None:
        write = terminalreporter.write_line
        if self.importer is None:
            write(f"steelix: {self.problem}", red=True)
            return
        names = list(self.importer.modules)
        imported = [name for name in names if name in sys.modules]
        native = [n for n in imported if loader_name(sys.modules[n]) == "NativeLoader"]
        write(
            f"steelix: {len(native)} of {len(names)} transpiled modules imported natively "
            f"from {self.importer.root}"
        )
        if self.problem is not None:
            write(f"steelix: {self.problem}", red=True)
        root = os.path.realpath(self.importer.root)
        others = sorted(
            name
            for name, module in list(sys.modules.items())
            if name not in names
            and within(getattr(module, "__file__", None), root)
            and loader_name(module) == "SourceFileLoader"
        )
        if others:
            write("steelix: not transpiled, imported from source: " + ", ".join(others))
        if terminalreporter.config.getoption("verbose") > 0:
            missing = [name for name in names if name not in sys.modules]
            if missing:
                write("steelix: not imported: " + ", ".join(missing))


def pytest_configure(config: pytest.Config) -> None:
    config.pluginmanager.register(NativeCheck(), f"{NAME}-check")
